// Command gensha1 emits the two independent SHA-NI lanes used by CPU mining.
package main

import (
	"bytes"
	"fmt"
	"os"
)

func main() {
	var out bytes.Buffer
	p := func(format string, args ...any) { fmt.Fprintf(&out, format+"\n", args...) }
	p("// Code generated by go run ./internal/gensha1; DO NOT EDIT.")
	p("//go:build amd64 && !purego\n\n#include \"textflag.h\"")
	p("\nTEXT ·hasSHAInstructions(SB), NOSPLIT, $0-1")
	p("\tMOVL $0, AX\n\tCPUID\n\tCMPL AX, $7\n\tJLT no_sha")
	p("\tMOVL $7, AX\n\tXORL CX, CX\n\tCPUID\n\tSHRL $29, BX\n\tANDL $1, BX\n\tMOVB BX, ret+0(FP)\n\tRET")
	p("no_sha:\n\tMOVB $0, ret+0(FP)\n\tRET")
	p("\n// output length must be even. Each lane hashes an independent timestamp.")
	p("TEXT ·sha1KeyIDsSHANI(SB), NOSPLIT, $0-40")
	p("\tMOVQ block+0(FP), SI\n\tMOVL timestamp+8(FP), R8\n\tMOVQ output_base+16(FP), DI\n\tMOVQ output_len+24(FP), R9")
	p("\tTESTQ R9, R9\n\tJE done\npair:")
	for lane := 0; lane < 2; lane++ {
		r := lane * 8
		p("\tMOVOU initialABCD<>(SB), X%d\n\tMOVOU initialE<>(SB), X%d", r, r+5)
		for word := 0; word < 4; word++ {
			p("\tMOVOU %d(SI), X%d\n\tPSHUFD $0x1b, X%d, X%d", word*16, r+word+1, r+word+1, r+word+1)
		}
		p("\tPINSRD $2, R8, X%d\n\tINCL R8", r+1)
	}
	for group := 0; group < 20; group++ {
		p("\n\t// Rounds %d-%d", group*4, group*4+3)
		// Interleave independent states so SHA instruction latency in one lane
		// overlaps useful work in the other. X1-X4/X9-X12 form schedule rings.
		for lane := 0; lane < 2; lane++ {
			r := lane * 8
			w := r + group%4 + 1
			e := r + 5 + group%2
			if group == 0 {
				p("\tPADDD X%d, X%d", w, e)
			} else {
				p("\tSHA1NEXTE X%d, X%d", w, e)
			}
			p("\tMOVOU X%d, X%d\n\tSHA1RNDS4 $%d, X%d, X%d", r, r+6-group%2, group/5, e, r)
		}
		for lane := 0; lane < 2; lane++ {
			r := lane * 8
			w := r + group%4 + 1
			if group >= 1 && group <= 16 {
				p("\tSHA1MSG1 X%d, X%d", w, r+(group-1)%4+1)
			}
			if group >= 2 && group <= 17 {
				p("\tPXOR X%d, X%d", w, r+(group-2)%4+1)
			}
			if group >= 3 && group <= 18 {
				p("\tSHA1MSG2 X%d, X%d", w, r+(group-3)%4+1)
			}
		}
	}
	for lane := 0; lane < 2; lane++ {
		r := lane * 8
		p("\n\tSHA1NEXTE initialE<>(SB), X%d\n\tMOVD X%d, AX\n\tADDL $0x10325476, AX", r+5, r)
		p("\tPEXTRD $3, X%d, DX\n\tSHLQ $32, AX\n\tORQ DX, AX\n\tMOVQ AX, %d(DI)", r+5, lane*8)
	}
	p("\tADDQ $16, DI\n\tSUBQ $2, R9\n\tJNZ pair\ndone:\n\tRET")
	p("\nDATA initialABCD<>+0(SB)/8, $0x98badcfe10325476\nDATA initialABCD<>+8(SB)/8, $0x67452301efcdab89\nGLOBL initialABCD<>(SB), RODATA, $16")
	p("\nDATA initialE<>+0(SB)/8, $0\nDATA initialE<>+8(SB)/4, $0\nDATA initialE<>+12(SB)/4, $0xc3d2e1f0\nGLOBL initialE<>(SB), RODATA, $16")
	if err := os.WriteFile("sha1batch_amd64.s", out.Bytes(), 0644); err != nil {
		panic(err)
	}
}
